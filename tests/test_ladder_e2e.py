def _load_gt() -> dict:
    return json.loads(GROUND_TRUTH.read_text())


def _region(gt: dict, region_id: str) -> dict:
    for r in gt["regions"]:
        if r["id"] == region_id:
            return r
    raise KeyError(f"region {region_id!r} not in ground truth")


# ---------------------------------------------------------------------------
# Candidate markdown, built from the committed ground truth (never hardcoded
# independently of it, so a fixture edit cannot silently desync the tests).
# ---------------------------------------------------------------------------


def _md(columns: list[str], rows: list[dict], row_label_order: list[str] | None = None) -> str:
    """Render a markdown table. ``row_label_order`` overrides which LABEL is
    printed for each positional row while keeping that row's own values --
    the shape a row-label-shift defect actually takes (values untouched,
    labels permuted)."""
    labels = row_label_order or [r["label"] for r in rows]
    header = "| Label | " + " | ".join(columns) + " |"
    sep = "| --- | " + " | ".join("---" for _ in columns) + " |"
    lines = [header, sep]
    for row, label in zip(rows, labels):
        lines.append(f"| {label} | " + " | ".join(row[c] for c in columns) + " |")
    return "\n".join(lines) + "\n"


_GT = _load_gt()
_CLEAN_REGION = _region(_GT, "clean_table")
_SHIFT_REGION = _region(_GT, "shift_table")

_CLEAN_ROWS = [
    {"label": lbl, "Value": _CLEAN_REGION["cells"][f"{lbl}|Value"]}
    for lbl in _CLEAN_REGION["row_labels"]
]
_SHIFT_ROWS = [
    {
        "label": lbl,
        "OLS": _SHIFT_REGION["cells"][f"{lbl}|OLS"],
        "IV": _SHIFT_REGION["cells"][f"{lbl}|IV"],
    }
    for lbl in _SHIFT_REGION["row_labels"]
]

CLEAN_MD = _md(_CLEAN_REGION["columns"], _CLEAN_ROWS)
SHIFT_CORRECT_MD = _md(_SHIFT_REGION["columns"], _SHIFT_ROWS)
SHIFT_SHIFTED_MD = _md(
    _SHIFT_REGION["columns"], _SHIFT_ROWS, row_label_order=_SHIFT_REGION["shifted_row_label_order"]
)

CLEAN_PAGE = _CLEAN_REGION["page"]
SHIFT_PAGE = _SHIFT_REGION["page"]


# ---------------------------------------------------------------------------
# Scripted rungs: decide verdict from the exact candidate markdown handed to
# them, so a single fake object serves every witnessed table across the
# whole document without ever running out of queued results.
# ---------------------------------------------------------------------------


def _pass_verdict(confidence: str = "high") -> TableJudgeVerdict:
    return TableJudgeVerdict(verdict="PASS", confidence=confidence, findings=[])


def _fail_verdict() -> TableJudgeVerdict:
    return TableJudgeVerdict(
        verdict="FAIL",
        confidence="high",
        findings=[Finding(code=FindingCode.WRONG_BINDING, where="row", detail="judge rejects")],
    )


class _ScriptedRung:
    """A ``RungCallable`` keyed by the exact candidate markdown text it is
    handed. Records every call for assertion (which table was actually
    judged, and with what ``prior_findings``)."""

    def __init__(self, verdicts: dict[str, RungResult], rung_id: str = "fake1") -> None:
        self._verdicts = verdicts
        self.rung_id = rung_id
        self.calls: list[tuple] = []

    def __call__(self, crop_path, markdown, prior_findings):
        self.calls.append((crop_path, markdown, prior_findings))
        key = markdown.strip()
        if key not in self._verdicts:
            raise AssertionError(f"unscripted markdown judged by {self.rung_id}: {key!r}")
        return self._verdicts[key]


