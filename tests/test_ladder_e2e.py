class TestRejectedTerminal:
    """Real judge FAIL on the shifted table -> TABLE_REJECTED, not retryable."""

    def test_flag_off_vs_on(self, tmp_path: Path, capsys) -> None:
        text_by_page = {CLEAN_PAGE: CLEAN_MD, SHIFT_PAGE: SHIFT_SHIFTED_MD}

        # -- flag off: baseline, both tables ship unchecked -----------------
        pdf_off = _fixture_copy(tmp_path, "off")
        _pipe_off, result_off, state_off = _run(
            pdf_off, tmp_path / "off_out", ladder_on=False, text_by_page=text_by_page, rungs=None
        )
        assert result_off.status == DocumentStatus.SUCCESS
        assert state_off.pages[CLEAN_PAGE].table_ladder_disposition is None
        assert state_off.pages[SHIFT_PAGE].table_ladder_disposition is None
        meta_off = _metadata(tmp_path / "off_out", pdf_off)
        assert meta_off["status"] != "partial"
        assert "table_rejected" not in json.dumps(meta_off)

        # -- flag on: shifted table rejected by the (real) judge ------------
        rung = _ScriptedRung(
            {
                CLEAN_MD.strip(): RungResult(rung="fake1", ok=True, verdict=_pass_verdict("high")),
                SHIFT_SHIFTED_MD.strip(): RungResult(
                    rung="fake1", ok=True, verdict=_fail_verdict()
                ),
            }
        )
        pdf_on = _fixture_copy(tmp_path, "on")
        _pipe_on, result_on, state_on = _run(
            pdf_on,
            tmp_path / "on_out",
            ladder_on=True,
            text_by_page=text_by_page,
            rungs=[rung],
        )

        # Page disposition: the demotion is per-page, not document-wide.
        # GH-575 (cold review round 1, finding 1): this fixture is a genuine
        # row-label shift, so native geometry ACTIVELY contradicts the emitted
        # grid -- and an active contradiction is terminal, ending the table
        # UNVERIFIED without asking the blind adjudicator. Withholding requires
        # a blind reader to have looked and disagreed, which cannot happen
        # here. Every surface below moves with the label; the
        # per-page-not-document-wide property this test exists for is
        # unchanged, and so is the flag-off/flag-on difference.
        assert state_on.pages[SHIFT_PAGE].table_ladder_disposition == FailureMode.TABLE_UNVERIFIED
        assert state_on.pages[CLEAN_PAGE].table_ladder_disposition is None

        # Document status.
        assert result_on.status == DocumentStatus.AUDIT_FAILED
        assert "table_unverified" in (result_on.error or "")
        assert str(SHIFT_PAGE) in (result_on.error or "")

        # metadata.json note.
        meta_on = _metadata(tmp_path / "on_out", pdf_on)
        assert meta_on["status"] == "partial"
        assert "table_unverified" in meta_on["error"]
        assert str(SHIFT_PAGE) in meta_on["error"]

        # CLI summary.
        _pipe_on._print_summary(result_on, state_on)
        captured = capsys.readouterr()
        assert "table_unverified" in captured.out


class TestPlainUnverifiedTerminal:
    """An infra (¬S1) rung on the CLEAN table -> TABLE_UNVERIFIED, retryable,
    with NO mechanical evidence involved -- the plain infra shape."""

    def test_flag_off_vs_on(self, tmp_path: Path, capsys) -> None:
        text_by_page = {CLEAN_PAGE: CLEAN_MD, SHIFT_PAGE: SHIFT_CORRECT_MD}

        pdf_off = _fixture_copy(tmp_path, "off")
        _pipe_off, result_off, state_off = _run(
            pdf_off, tmp_path / "off_out", ladder_on=False, text_by_page=text_by_page, rungs=None
        )
        assert result_off.status == DocumentStatus.SUCCESS
        meta_off = _metadata(tmp_path / "off_out", pdf_off)
        assert "table_unverified" not in json.dumps(meta_off)

        rung = _ScriptedRung(
            {
                SHIFT_CORRECT_MD.strip(): RungResult(
                    rung="fake1", ok=True, verdict=_pass_verdict("high")
                ),
                CLEAN_MD.strip(): RungResult(
                    rung="fake1", ok=False, error="simulated infra failure"
                ),
            }
        )
        pdf_on = _fixture_copy(tmp_path, "on")
        _pipe_on, result_on, state_on = _run(
            pdf_on,
            tmp_path / "on_out",
            ladder_on=True,
            text_by_page=text_by_page,
            rungs=[rung],
        )

        assert state_on.pages[CLEAN_PAGE].table_ladder_disposition == FailureMode.TABLE_UNVERIFIED
        assert state_on.pages[SHIFT_PAGE].table_ladder_disposition is None

        assert result_on.status == DocumentStatus.AUDIT_FAILED
        assert "table_unverified" in (result_on.error or "")
        assert str(CLEAN_PAGE) in (result_on.error or "")

        meta_on = _metadata(tmp_path / "on_out", pdf_on)
        assert meta_on["status"] == "partial"
        assert "table_unverified" in meta_on["error"]

        _pipe_on._print_summary(result_on, state_on)
        captured = capsys.readouterr()
        assert "table_unverified" in captured.out

        # Distinguish from the CLAMPED case below: no mechanical wording.
        unverified_events = [e for e in state_on.events if e.kind == TABLE_LADDER_UNVERIFIED_KIND]
        assert unverified_events
        assert all("mechanical binding check" not in e.detail for e in unverified_events)


class TestClampedUnverifiedTerminal:
    """Mechanical contradiction on the shifted table + a high-confidence real
    PASS -> CONSILIUM's clamp caps the table at UNVERIFIED (never silently
    ACCEPTED, never REJECTED by the clamp alone) -- distinct from plain
    infra UNVERIFIED by both its trigger (S1 held; the judge DID answer) and
    its audit-event wording."""

    def test_flag_off_vs_on(self, tmp_path: Path, capsys) -> None:
        text_by_page = {CLEAN_PAGE: CLEAN_MD, SHIFT_PAGE: SHIFT_SHIFTED_MD}

        pdf_off = _fixture_copy(tmp_path, "off")
        _pipe_off, result_off, state_off = _run(
            pdf_off, tmp_path / "off_out", ladder_on=False, text_by_page=text_by_page, rungs=None
        )
        assert result_off.status == DocumentStatus.SUCCESS
        meta_off = _metadata(tmp_path / "off_out", pdf_off)
        assert "table_unverified" not in json.dumps(meta_off)

        # Both tables get a high-confidence real PASS -- the ladder alone
        # would ACCEPT both; only the mechanical clamp demotes the shifted one.
        rung = _ScriptedRung(
            {
                CLEAN_MD.strip(): RungResult(rung="fake1", ok=True, verdict=_pass_verdict("high")),
                SHIFT_SHIFTED_MD.strip(): RungResult(
                    rung="fake1", ok=True, verdict=_pass_verdict("high")
                ),
            }
        )
        pdf_on = _fixture_copy(tmp_path, "on")
        _pipe_on, result_on, state_on = _run(
            pdf_on,
            tmp_path / "on_out",
            ladder_on=True,
            text_by_page=text_by_page,
            rungs=[rung],
        )

        # GH-359 ruling 4: the real rung does NOT see mechanical findings
        # (crop + markdown, nothing else). Ruling 5: the clamp still fires.
        shift_calls = [c for c in rung.calls if c[1].strip() == SHIFT_SHIFTED_MD.strip()]
        assert shift_calls
        assert shift_calls[0][2] is None

        assert state_on.pages[SHIFT_PAGE].table_ladder_disposition == FailureMode.TABLE_UNVERIFIED
        assert state_on.pages[CLEAN_PAGE].table_ladder_disposition is None

        assert result_on.status == DocumentStatus.AUDIT_FAILED
        assert "table_unverified" in (result_on.error or "")
        assert str(SHIFT_PAGE) in (result_on.error or "")

        meta_on = _metadata(tmp_path / "on_out", pdf_on)
        assert meta_on["status"] == "partial"
        assert "table_unverified" in meta_on["error"]

        _pipe_on._print_summary(result_on, state_on)
        captured = capsys.readouterr()
        assert "table_unverified" in captured.out

        # The distinguishing wording from plain infra UNVERIFIED.
        unverified_events = [e for e in state_on.events if e.kind == TABLE_LADDER_UNVERIFIED_KIND]
        assert unverified_events
        assert any(
            "mechanical binding check found a contradiction" in e.detail for e in unverified_events
        )
