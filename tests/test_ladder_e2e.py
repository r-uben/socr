"""TICKET-H1 (GH-353): end-to-end table judge ladder + committed fixture.

The final ticket of the table-judge-ladder initiative. Everything upstream
(A0-A4, B0-B2, C1-C3, D1a-D1b, E1) is unit/gate-level; this file is the one
place that drives the REAL ``UnifiedPipeline.process()`` on a REAL,
COMMITTED, two-page PDF (``tests/fixtures/table_ladder/``, generated by
``generate_fixture.py`` -- see that module's own docstring and
``tests/fixtures/table_repair/generate_fixture.py``'s precedent) and walks
every terminal the ladder can reach through all four no-silent-loss
surfaces: page disposition, document status, ``metadata.json`` note, and the
CLI summary line (``result.error`` as printed by ``_print_summary``).

The fixture's page 2 reproduces the GH-273 shape: a row-label rotation that
keeps every value in the table (an identical multiset) but binds each value
to the WRONG row label -- the defect two frontier judges both missed
(``docs/log/2026-08-30_table-judge-ladder.md``). Page 1 is a clean,
unambiguous control table with no such shape.

Three terminal scenarios, each contrasting a demoted page against an
ACCEPTED page in the SAME document (proving the demotion is per-page, not a
silent document-wide sweep):

- REJECTED: the (real, injected) judge itself answers FAIL on the shifted
  table -- a content verdict, not retryable.
- Plain UNVERIFIED: an infra (¬S1) rung on the CLEAN table -- nobody could
  look, no mechanical evidence involved at all.
- CLAMPED-UNVERIFIED (E1's flag in STATUS.md): the mechanical binding check
  finds a genuine contradiction on the shifted table AND the real judge
  answers a high-confidence PASS -- CONSILIUM's clamp caps that at
  UNVERIFIED rather than letting the judge's PASS silently erase the
  mechanical evidence (the exact GH-273 failure). Distinguished from plain
  UNVERIFIED by its own audit-event wording ("mechanical binding check found
  a contradiction").

Hermetic throughout, matching every prior GH-353 ticket's own contract: CI
has no ollama and no ``gemini`` binary, so every rung is an injected fake
that decides its verdict from the candidate markdown text it is handed (no
queue-exhaustion risk across the two witnessed tables in one document, since
``_build_table_judge_rungs()`` is called ONCE per document and its rungs are
reused for every page/table -- see ``orchestrator.py:3207``).
``_available_engines_for_agentic`` and ``_resolve_judge_model`` are patched
so the OCR provider ladder and judge-model resolution never touch a live
daemon. Per the #253/#257 trap, every scenario runs flag-off THEN flag-on in
one test and asserts the DELTA the flag makes -- never an absolute outcome
tuple pinned from one machine.

Resume interaction (REJECTED skips on resume, UNVERIFIED reprocesses) is
already covered exhaustively at the production seam
(``_load_terminal_page``) by ``tests/test_ladder_resume.py`` (TICKET-D1b);
repeating it here at the full-``process()`` level would only re-exercise
that same seam through more machinery for no new coverage, so it is
intentionally left to D1b.
"""

