class TestFixtureSanity:
    def test_pdf_and_ground_truth_exist(self) -> None:
        assert FIXTURE_PDF.exists()
        assert GROUND_TRUTH.exists()

    def test_two_pages_born_digital(self) -> None:
        doc = fitz.open(str(FIXTURE_PDF))
        assert doc.page_count == 2
        for i in range(2):
            assert len(doc[i].get_text("words")) >= 6
        doc.close()

    def test_ground_truth_two_table_regions(self) -> None:
        gt = _load_gt()
        assert [r["id"] for r in gt["regions"]] == ["clean_table", "shift_table"]

    def test_shifted_row_label_order_is_a_permutation_not_identity(self) -> None:
        region = _region(_load_gt(), "shift_table")
        shifted = region["shifted_row_label_order"]
        assert sorted(shifted) == sorted(region["row_labels"])
        assert shifted != region["row_labels"]

    def test_shifted_markdown_preserves_the_value_multiset(self) -> None:
        """The GH-273 shape itself: SHIFT_SHIFTED_MD carries the exact same
        multiset of values as SHIFT_CORRECT_MD -- only row/label binding
        differs, so a value-presence-only check cannot tell them apart."""
        import re

        def _values(md: str) -> list[str]:
            vals = []
            for line in md.splitlines()[2:]:
                cells = [c.strip() for c in line.strip("|").split("|")]
                vals.extend(cells[1:])
            return sorted(vals)

        assert _values(SHIFT_SHIFTED_MD) == _values(SHIFT_CORRECT_MD)
        assert SHIFT_SHIFTED_MD != SHIFT_CORRECT_MD


