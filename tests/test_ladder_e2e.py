def _make_config(
    table_judge_ladder: bool = False,
    **overrides,
) -> PipelineConfig:
    kwargs = dict(
        primary_engine=EngineType.QWEN,
        agentic=True,
        judge_backend="heuristic",
        enabled_engines=[EngineType.QWEN],
        quiet=True,
        save_figures=False,
        write_manifest=False,
    )
    kwargs.update(overrides)
    return PipelineConfig(
        table_judge_ladder=table_judge_ladder,  # docs/log/2026-09-03_p1-prep-latch-and-audit.md
        **kwargs,
    )


def _route_page_per_page(text_by_page: dict[int, str]):
    def _fake_route(page_num, ladder, run_provider, judge, **kwargs):
        from socr.pipeline.agentic import PageDecision, ProviderAttempt

        text = text_by_page[page_num]
        out = PageOutput(
            page_num=page_num,
            text=text,
            status=PageStatus.SUCCESS,
            engine="qwen",
            audit_passed=True,
        )
        prof = ladder[0]
        att = ProviderAttempt(
            engine=prof.engine,
            output=out,
            cost_usd=prof.cost_per_page_usd,
            accepted=True,
            reason="ok",
            provider_id=prof.id,
            model=prof.model,
            backend=prof.backend,
        )
        return PageDecision(page_num=page_num, final_output=out, attempts=[att], accepted=True)

    return _fake_route


def _process_and_capture(
    pipeline: UnifiedPipeline, pdf_path: Path, out_dir: Path
) -> tuple[object, object]:
    """Run ``process()`` and also return the ``DocumentState`` it built, by
    spying on ``_phase_assemble`` (the only seam holding a reference to it) --
    so the CLI summary surface (``_print_summary``, which takes ``state``)
    can be exercised against the SAME run the document/metadata assertions
    check, without process() itself needing to expose ``state``."""
    captured: dict[str, object] = {}
    original = pipeline._phase_assemble

    def _spy(state, out_dir_):
        captured["state"] = state
        return original(state, out_dir_)

    with patch.object(pipeline, "_phase_assemble", side_effect=_spy):
        result = pipeline.process(pdf_path, out_dir)
    return result, captured["state"]


def _run(
    pdf_path: Path,
    out_dir: Path,
    *,
    ladder_on: bool,
    text_by_page: dict[int, str],
    rungs: list | None,
):
    cfg = _make_config(table_judge_ladder=ladder_on)
    pipeline = UnifiedPipeline(cfg)
    patches = [
        patch(
            "socr.pipeline.orchestrator.route_page",
            side_effect=_route_page_per_page(text_by_page),
        ),
        patch.object(pipeline, "_available_engines_for_agentic", return_value=[PROFILE_QWEN_LOCAL]),
        patch.object(pipeline, "_resolve_judge_model", return_value=""),
    ]
    if ladder_on:
        patches.append(patch.object(pipeline, "_build_table_judge_rungs", return_value=rungs or []))
    with contextlib.ExitStack() as stack:
        for p in patches:
            stack.enter_context(p)
        result, state = _process_and_capture(pipeline, pdf_path, out_dir)
    return pipeline, result, state


def _metadata(out_dir: Path, pdf_path: Path) -> dict:
    doc_dir = out_dir / pdf_path.stem
    return json.loads((doc_dir / "metadata.json").read_text(encoding="utf-8"))


def _fixture_copy(tmp_path: Path, name: str) -> Path:
    dest = tmp_path / name
    dest.mkdir(parents=True, exist_ok=True)
    pdf_path = dest / "binding_shift_doc.pdf"
    shutil.copyfile(FIXTURE_PDF, pdf_path)
    return pdf_path


